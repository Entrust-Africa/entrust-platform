// seven categories with their points, the scoring guidance for each, the evidence an officer looks for, and
// the rule for category D. APPROVED, so it never changes: put a correction in a new version.
//
// What the scorecard leaves out, decided here:
// - It has one set of criteria for every pathway, so no criterion is limited to a pathway. An investment
//   applicant is scored on trade (category C) like the rest, as the scorecard says, and a trade applicant on
//   everything except category D.
// - The minimum documents for eligibility (the scorecard doesn't give them) are kept small, since the scorecard
//   rewards evidence in points: an applicant is not turned away before assessment for lacking a document the
//   scorecard would only mark down. Financial statements are restricted, so none is required.

