/** A cell of an exported table: text, a figure, or nothing. */
export type ExportCell = string | number | null;

/** A table with what the specification's general export rules say every report carries. */
export interface ExportTable {
  /** The Summit's name, for the head of a PDF. */
  summit: string;
  /** Report name. */
  title: string;
  purpose: string;
  /** Reporting period or application cycle. */
  period: string;
  generatedAt: Date;
  /** The user who generated the report. */
  generatedBy: string;
  /** The filters applied, in words. */
  filters: string;
  /** Total number of records included. */
  records: number;
  /** Confidentiality classification, in words. */
  classification: string;
  columns: readonly { key: string; label: string; numeric: boolean }[];
  rows: readonly (readonly ExportCell[])[];
  /** A PDF puts a block per row, headed by this many of its first cells. */
  titleCells: number;
}

/** The lines every format shows above or beside the records. */
export function detailsOf(table: ExportTable): [string, string][] {
  return [
    ["Summit", table.summit],
    ["Report", table.title],
    ["Reporting period", table.period],
    ["Generated", table.generatedAt.toISOString().replace("T", " ").slice(0, 19) + " UTC"],
    ["Generated by", table.generatedBy],
    ["Filters applied", table.filters],
    ["Total records", String(table.records)],
    ["Classification", table.classification],
  ];
}

const NUMBER = new Intl.NumberFormat("en-US", { maximumFractionDigits: 2 });

/** A cell as text for a person reading it. */
export const displayCell = (cell: ExportCell): string => (cell === null ? "" : typeof cell === "number" ? NUMBER.format(cell) : cell);
